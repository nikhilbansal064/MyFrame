-- Supabase Database Migration
-- Target: 'My Story' Web Application Schema (Zero-Migration Postgres Layout)

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- ==========================================
-- 1. TABLES CREATION
-- ==========================================

-- Table: organisers
create table if not exists public.organisers (
  id uuid references auth.users on delete cascade primary key,
  email text not null,
  full_name text,
  avatar_url text,
  is_public boolean default true not null,            -- Profile visibility controls
  settings jsonb default '{}'::jsonb not null,        -- Future-proofing: brand colors, pricing plans
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Table: frames (Decoupled overlays)
create table if not exists public.frames (
  id uuid default gen_random_uuid() primary key,
  url text not null,                                  -- Firebase/Supabase Storage frame PNG URL
  title text,                                         -- Optional display name
  creator_id uuid references public.organisers(id) on delete set null, -- Null for system/admin frames
  is_system boolean default false not null,           -- true for pre-uploaded system-wide frames
  is_public boolean default true not null,            -- Governs public gallery visibility
  usage_count integer default 0 not null,             -- Incremented via increment_frame_usage RPC
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Table: campaigns
create table if not exists public.campaigns (
  id uuid default gen_random_uuid() primary key,
  slug text unique not null,
  creator_id uuid references public.organisers(id) on delete cascade not null,
  title text not null,
  description text,
  frame_id uuid references public.frames(id) on delete restrict not null, -- Decoupled frame reference
  start_date timestamp with time zone not null,
  end_date timestamp with time zone not null,
  is_active boolean default true not null,
  is_public boolean default true not null,            -- Campaign visibility controls
  settings jsonb default '{}'::jsonb not null,        -- Future-proofing: scale sliders, border styles
  metadata jsonb default '{}'::jsonb not null,        -- Future-proofing: categories, SEO tags
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Table: participants
create table if not exists public.participants (
  id bigint generated by default as identity primary key,
  campaign_id uuid references public.campaigns(id) on delete set null, -- Nullable for standalone frames (Trendy Frames)
  frame_id uuid references public.frames(id) on delete cascade not null, -- Always links to a frame
  event_type text not null check (event_type in ('view', 'download')),
  user_agent text,                                    -- Logs client OS, device, browser telemetry
  locale text,                                        -- e.g. "en-IN", "en-US"
  region text,                                        -- Timezone or location region
  metadata jsonb default '{}'::jsonb not null,        -- Future-proofing: social share channel, screen resolution
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Indexes for scaling performance
create index if not exists idx_participants_campaign_id on public.participants(campaign_id);
create index if not exists idx_participants_frame_id on public.participants(frame_id);
create index if not exists idx_frames_usage_count on public.frames(usage_count desc);

-- ==========================================
-- 2. DYNAMIC ANALYTICS VIEWS
-- ==========================================

-- Daily Stats View (Views vs Downloads)
create or replace view public.campaign_daily_stats as
select
  campaign_id,
  date_trunc('day', created_at) as event_date,
  event_type,
  count(*) as event_count
from public.participants
where campaign_id is not null
group by campaign_id, date_trunc('day', created_at), event_type;

-- Device Telemetry Grouping View
create or replace view public.campaign_device_stats as
select
  campaign_id,
  case 
    when user_agent ilike '%mobile%' then 'Mobile'
    when user_agent ilike '%tablet%' then 'Tablet'
    else 'Desktop'
  end as device_category,
  count(*) as event_count
from public.participants
where campaign_id is not null
group by campaign_id, device_category;

-- Frame-Level Daily Stats View
create or replace view public.frame_daily_stats as
select
  frame_id,
  date_trunc('day', created_at) as event_date,
  event_type,
  count(*) as event_count
from public.participants
group by frame_id, date_trunc('day', created_at), event_type;

-- ==========================================
-- 3. AUTOMATIC PROFILE SYNC ON USER SIGN-UP
-- ==========================================

create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.organisers (id, email, full_name, avatar_url, is_public, settings)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    coalesce(new.raw_user_meta_data->>'avatar_url', ''),
    true,
    '{}'::jsonb
  )
  on conflict (id) do update
  set 
    email = excluded.email,
    full_name = excluded.full_name,
    avatar_url = excluded.avatar_url;
  return new;
end;
$$ language plpgsql security definer;

-- Trigger to fire sync whenever an auth user is created (e.g., Google OAuth)
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- ==========================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- ==========================================

-- Enable RLS across all tables
alter table public.organisers enable row level security;
alter table public.frames enable row level security;
alter table public.campaigns enable row level security;
alter table public.participants enable row level security;

-- 4.1 Organisers Policies
create policy "Allow public read of public profiles" on public.organisers
  for select using (is_public = true or auth.uid() = id);

create policy "Allow organisers to update their own profile" on public.organisers
  for update using (auth.uid() = id);

-- 4.2 Frames Policies
create policy "Allow public read of public or system frames" on public.frames
  for select using (is_public = true or is_system = true or auth.uid() = creator_id);

create policy "Allow organisers to insert their own frames" on public.frames
  for insert with check (auth.uid() = creator_id);

create policy "Allow organisers to update their own frames" on public.frames
  for update using (auth.uid() = creator_id);

create policy "Allow organisers to delete their own frames" on public.frames
  for delete using (auth.uid() = creator_id);

-- 4.3 Campaigns Policies
create policy "Allow public read of active and public campaigns" on public.campaigns
  for select using (
    (is_active = true and is_public = true)
    or auth.uid() = creator_id
  );

create policy "Allow organisers to insert campaigns" on public.campaigns
  for insert with check (auth.uid() = creator_id);

create policy "Allow organisers to update their own campaigns" on public.campaigns
  for update using (auth.uid() = creator_id);

create policy "Allow organisers to delete their own campaigns" on public.campaigns
  for delete using (auth.uid() = creator_id);

-- 4.4 Participants Policies
create policy "Allow anyone to record participant events" on public.participants
  for insert with check (true);

create policy "Allow organisers to view event telemetry for their campaigns" on public.participants
  for select using (
    auth.uid() = (
      select creator_id 
      from public.campaigns 
      where campaigns.id = participants.campaign_id
    )
    or
    auth.uid() = (
      select creator_id
      from public.frames
      where frames.id = participants.frame_id
    )
  );

-- ==========================================
-- 5. RPC FUNCTIONS FOR HIGH CONCURRENCY
-- ==========================================

-- RPC utility function to atomically increment usage count (bypasses direct write lock on campaign)
create or replace function public.increment_frame_usage(frame_id uuid)
returns void as $$
begin
  update public.frames
  set usage_count = usage_count + 1
  where id = frame_id;
end;
$$ language plpgsql security definer;

-- ==========================================
-- 6. STORAGE BUCKET CONFIGURATION & POLICIES
-- ==========================================

-- Insert frame public storage bucket
insert into storage.buckets (id, name, public)
values ('campaign-frames', 'campaign-frames', true)
on conflict (id) do nothing;

-- Storage Security Policies
drop policy if exists "Public Access to Storage Frames" on storage.objects;
create policy "Public Access to Storage Frames" on storage.objects
  for select using (bucket_id = 'campaign-frames');

-- Restrict inserts to path formats structured as 'frames/USER_ID/...' to secure multi-tenant isolation
drop policy if exists "Authenticated Organisers can upload frames" on storage.objects;
create policy "Authenticated Organisers can upload frames" on storage.objects
  for insert with check (
    bucket_id = 'campaign-frames' 
    and auth.role() = 'authenticated'
    and (storage.foldername(name))[1] = 'frames'
    and (storage.foldername(name))[2] = auth.uid()::text
  );

-- Restrict mutations (update/delete) exclusively to path owners
drop policy if exists "Organisers can update/delete their own frames" on storage.objects;
create policy "Organisers can update/delete their own frames" on storage.objects
  for all using (
    bucket_id = 'campaign-frames' 
    and auth.role() = 'authenticated'
    and (storage.foldername(name))[1] = 'frames'
    and (storage.foldername(name))[2] = auth.uid()::text
  );
